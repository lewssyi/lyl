#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
TARGET_PATH="${1:-${LFTS_LIME_DCCS_TARGET_PATH:-${PROJECT_DIR}/outputs/lime_dccs_targets.npz}}"

cd "${PROJECT_DIR}"

if [[ ! -f "${TARGET_PATH}" ]]; then
  echo "LIME-DCCS target file not found:"
  echo "  ${TARGET_PATH}"
  echo
  echo "Expected an .npz containing train_lime_dccs_targets, train_confidence, and train_predicted_labels."
  echo "Pass a target path explicitly if it lives elsewhere, for example:"
  echo "  bash scripts/run_server_lime_dccs.sh /home/b502/wssyi/LIME-for-Time-Series/outputs/lime_dccs_targets.npz"
  exit 1
fi

export LFTS_CUDA_VISIBLE_DEVICES="${LFTS_CUDA_VISIBLE_DEVICES:-0,6,7}"
export LFTS_REQUIRE_REQUESTED_GPUS="${LFTS_REQUIRE_REQUESTED_GPUS:-1}"
export LFTS_PER_REPLICA_BATCH_SIZE="${LFTS_PER_REPLICA_BATCH_SIZE:-11}"
export LFTS_PREDICT_PER_REPLICA_BATCH_SIZE="${LFTS_PREDICT_PER_REPLICA_BATCH_SIZE:-8}"

export LFTS_EXPLANATION_FEEDBACK_MODE="${LFTS_EXPLANATION_FEEDBACK_MODE:-clinical_calibrated_lime_dccs}"
export LFTS_EXPLANATION_FEEDBACK_TRAINING="${LFTS_EXPLANATION_FEEDBACK_TRAINING:-1}"
export LFTS_LIME_DCCS_TARGET_PATH="${LFTS_LIME_DCCS_TARGET_PATH:-${TARGET_PATH}}"

export LFTS_SELECTOR_MODE="${LFTS_SELECTOR_MODE:-accuracy_macro}"
export LFTS_VALIDATION_HMM_EMISSION_WEIGHTS="${LFTS_VALIDATION_HMM_EMISSION_WEIGHTS:-0.85,1.05,1.10,1.15,1.20,1.25,1.30}"

export LFTS_LIME_DCCS_ALPHA="${LFTS_LIME_DCCS_ALPHA:-0.25}"
export LFTS_LIME_DCCS_BETA="${LFTS_LIME_DCCS_BETA:-0.35}"
export LFTS_LIME_DCCS_GAMMA="${LFTS_LIME_DCCS_GAMMA:-0.40}"
export LFTS_LIME_DCCS_FEEDBACK_FILTER="${LFTS_LIME_DCCS_FEEDBACK_FILTER:-correct_and_high_confidence}"
export LFTS_LIME_DCCS_MIN_CONFIDENCE="${LFTS_LIME_DCCS_MIN_CONFIDENCE:-0.70}"
export LFTS_LIME_DCCS_USE_VAL_FEEDBACK="${LFTS_LIME_DCCS_USE_VAL_FEEDBACK:-0}"
export LFTS_LIME_DCCS_SOFT_SAMPLE_WEIGHTS="${LFTS_LIME_DCCS_SOFT_SAMPLE_WEIGHTS:-1}"

export LFTS_ATTENTION_FEEDBACK_LOSS_WEIGHT="${LFTS_ATTENTION_FEEDBACK_LOSS_WEIGHT:-0.01}"
export LFTS_CONCEPT_BOTTLENECK_LOSS_WEIGHT="${LFTS_CONCEPT_BOTTLENECK_LOSS_WEIGHT:-0.01}"
export LFTS_CONCEPT_OUTPUT_LOSS_WEIGHT="${LFTS_CONCEPT_OUTPUT_LOSS_WEIGHT:-0.05}"
export LFTS_AUX_FEEDBACK_WARMUP_EPOCHS="${LFTS_AUX_FEEDBACK_WARMUP_EPOCHS:-3}"
export LFTS_AUX_FEEDBACK_RAMP_EPOCHS="${LFTS_AUX_FEEDBACK_RAMP_EPOCHS:-5}"

export LFTS_RUN_REPRESENTATIVE_XAI="${LFTS_RUN_REPRESENTATIVE_XAI:-0}"
export LFTS_RUN_TRANSITION_XAI="${LFTS_RUN_TRANSITION_XAI:-0}"
export LFTS_REPRESENTATIVE_XAI_PERTURBATIONS="${LFTS_REPRESENTATIVE_XAI_PERTURBATIONS:-120}"
export LFTS_TRANSITION_XAI_PERTURBATIONS="${LFTS_TRANSITION_XAI_PERTURBATIONS:-80}"
export LFTS_TRANSITION_XAI_WINDOW_RADIUS="${LFTS_TRANSITION_XAI_WINDOW_RADIUS:-1}"
export LFTS_MAX_TRANSITION_XAI_DASHBOARDS="${LFTS_MAX_TRANSITION_XAI_DASHBOARDS:-3}"

echo "Running LIME-DCCS feedback training on server"
echo "  project: ${PROJECT_DIR}"
echo "  target:  ${LFTS_LIME_DCCS_TARGET_PATH}"
echo "  gpus:    ${LFTS_CUDA_VISIBLE_DEVICES}"
echo "  mode:    ${LFTS_EXPLANATION_FEEDBACK_MODE}"
echo "  selector:${LFTS_SELECTOR_MODE}"
echo "  xai:     representative=${LFTS_RUN_REPRESENTATIVE_XAI}, transition=${LFTS_RUN_TRANSITION_XAI}"

python run_main.py
